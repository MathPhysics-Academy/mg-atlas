#!/usr/bin/env python3
"""Generate baseline Lean certificates from GAP action data."""
import json
from collections import deque
from math import lcm
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
PRELUDE = r'''import Mathlib.Data.Fin.Basic
import Lean.Util.CollectAxioms

/- Generated by lean/generate_baseline.py from results/gap-actions.jsonl.
   These are certificates for supplied actions, not proofs of the generating
   pair enumeration, the group labels, or the geometric interpretation. -/
namespace ChenBaseline

inductive Letter where
  | s | t
  deriving DecidableEq, Repr
open Letter
abbrev Word := List Letter

def act {n : Nat} (S T : Fin n → Fin n) (p : Fin n) (w : Word) : Fin n :=
  w.foldl (fun q a => match a with | s => S q | t => T q) p

def follows {n : Nat} (T : Fin n → Fin n) (c : List (Fin n)) : Bool :=
  !c.isEmpty && (c.zip (c.drop 1 ++ c.take 1)).all (fun pq => T pq.1 == pq.2)

-- The short linear-size quotient certificate implies the exact fiber relation.
theorem central_fibers {α β : Type} (z : α → α)
    (involutive : ∀ p, z (z p) = p) (cls : α → β) (rep : β → α)
    (invariant : ∀ p, cls (z p) = cls p)
    (cover : ∀ p, rep (cls p) = p ∨ rep (cls p) = z p) (p q : α) :
    cls p = cls q ↔ q = p ∨ q = z p := by
  constructor
  · intro h
    have hr := congrArg rep h
    rcases cover p with hp | hp <;> rcases cover q with hq | hq
    · exact Or.inl (hq.symm.trans (hr.symm.trans hp))
    · right
      have he : p = z q := hp.symm.trans (hr.trans hq)
      exact ((congrArg z he).trans (involutive q)).symm
    · exact Or.inr (hq.symm.trans (hr.symm.trans hp))
    · left
      have he : z q = z p := hq.symm.trans (hr.symm.trans hp)
      exact (involutive q).symm.trans ((congrArg z he).trans (involutive p))
  · rintro (h | h)
    · rw [h]
    · rw [h, invariant p]

structure ResidueMatrix (N : Nat) where
  a : Fin N
  b : Fin N
  c : Fin N
  d : Fin N
  deriving DecidableEq, Repr

def matrixStep {N : Nat} (positive : 0 < N) (m : ResidueMatrix N) :
    Letter → ResidueMatrix N
  | s => ⟨m.b, ⟨(N - m.a.val) % N, Nat.mod_lt _ positive⟩,
           m.d, ⟨(N - m.c.val) % N, Nat.mod_lt _ positive⟩⟩
  | t => ⟨m.a, ⟨(m.a.val + m.b.val) % N, Nat.mod_lt _ positive⟩,
           m.c, ⟨(m.c.val + m.d.val) % N, Nat.mod_lt _ positive⟩⟩

def matrixOf (N : Nat) (positive : 0 < N) (w : Word) : ResidueMatrix N :=
  w.foldl (matrixStep positive)
    ⟨⟨1 % N, Nat.mod_lt _ positive⟩, ⟨0, positive⟩,
     ⟨0, positive⟩, ⟨1 % N, Nat.mod_lt _ positive⟩⟩

-- Soundness of the obstruction: no search algorithm is trusted by this proof.
theorem collision_obstructs {N n : Nat} (positive : 0 < N)
    (S T : Fin n → Fin n) (p : Fin n) (u v : Word)
    (hm : matrixOf N positive u = matrixOf N positive v)
    (hp : act S T p u ≠ act S T p v) :
    ¬ ∃ f : ResidueMatrix N → Fin n,
        ∀ w : Word, f (matrixOf N positive w) = act S T p w := by
  rintro ⟨f, hf⟩
  have h := congrArg f hm
  rw [hf u, hf v] at h
  exact hp h

'''
AUDIT = r'''
-- Audit all transitive dependencies, including generated auxiliary definitions.
run_cmd do
  let allowed : Array Lean.Name := #[``propext, ``Classical.choice, ``Quot.sound]
  let mut count : Nat := 0
  for (name, _) in (← Lean.getEnv).constants.toList do
    if name.toString.startsWith "ChenBaseline." then
      for ax in (← Lean.collectAxioms name) do
        unless allowed.contains ax do
          throwError "Axiom audit failed: {name} depends on {ax}"
      count := count + 1
  Lean.logInfo m!"Axiom audit passed for all {count} ChenBaseline declarations; allowed: {allowed}"

end ChenBaseline
'''

def literal(xs):
    return '[' + ','.join((literal(x) if isinstance(x, list) else str(x) for x in xs)) + ']'

def word(w):
    return '[' + ','.join(w) + ']'

def balanced_lookup(values, start=0):
    """Lean expression selecting a literal using logarithmic-depth comparisons."""
    if len(values) == 1:
        return values[0]
    half = len(values) // 2
    return (f'if p.val < {start + half} then ({balanced_lookup(values[:half], start)}) '
            f'else ({balanced_lookup(values[half:], start + half)})')

def lookup_tree(values, start=0):
    if len(values) == 1:
        return f'(.leaf ({values[0]}))'
    half = len(values) // 2
    return (f'(.branch {start + half} {lookup_tree(values[:half], start)} '
            f'{lookup_tree(values[half:], start + half)})')

def function(name, values, domain, codomain, balanced=False, tree=False):
    if tree:
        return (f'def {name}Data : LookupTree (Fin {codomain}) :=\n'
                f'  {lookup_tree(list(map(str, values)))}\n'
                f'def {name} (p : Fin {domain}) : Fin {codomain} :=\n'
                f'  tableLookup {name}Data p.val\n')
    if balanced:
        return (f'def {name} (p : Fin {domain}) : Fin {codomain} :=\n'
                f'  {balanced_lookup(list(map(str, values)))}\n')
    return (f'def {name} (p : Fin {domain}) : Fin {codomain} :=\n'
            f'  (#{literal(values)} : Array (Fin {codomain}))[p.val]’(by simp)\n').replace('’', "'")

def perm(name, values, balanced=False, tree=False):
    inverse = [values.index(i) for i in range(len(values))]
    n = len(values)
    return function(name + 'Map', values, n, n, balanced, tree) + function(name + 'Inv', inverse, n, n, balanced, tree) + f'def {name} : Equiv.Perm (Fin {n}) where\n' + f'  toFun := {name}Map\n  invFun := {name}Inv\n' + f'  left_inv := by\n    change ∀ p : Fin {n}, {name}Inv ({name}Map p) = p\n    decide\n' + f'  right_inv := by\n    change ∀ p : Fin {n}, {name}Map ({name}Inv p) = p\n    decide\n'

def paths(S, T):
    words = {0: []}
    q = deque([0])
    while q:
        p = q.popleft()
        for perm_, letter in [(S, 's'), (T, 't')]:
            t = perm_[p]
            if t not in words:
                words[t] = words[p] + [letter]
                q.append(t)
    assert len(words) == len(S)
    return [words[i] for i in range(len(S))]

def cycles(T):
    unseen = set(range(len(T)))
    cs = []
    while unseen:
        p = min(unseen)
        c = []
        while p in unseen:
            c.append(p)
            unseen.remove(p)
            p = T[p]
        assert p == c[0]
        cs.append(c)
    return sorted(cs, key=lambda c: (len(c), c))

def collision(S, T, N):
    identity = (1 % N, 0, 0, 1 % N)
    seen = {identity: (0, [])}
    q = deque([identity])
    while q:
        m = q.popleft()
        p, w = seen[m]
        a, b, c, d = m
        steps = [((b, -a % N, d, -c % N), S[p], 's'), ((a, (a + b) % N, c, (c + d) % N), T[p], 't')]
        for nxt, point, letter in steps:
            if nxt in seen:
                if seen[nxt][0] != point:
                    return (seen[nxt][1], w + [letter])
            else:
                seen[nxt] = (point, w + [letter])
                q.append(nxt)
    raise ValueError(f'No obstruction at modulus {N}')

def component(group, number, c, baseline):
    S, T = (c['S'], c['T'])
    n = len(S)
    balanced = group.get('balanced', False)
    tree = group.get('tree_lookup', False)
    cls = [-1] * n
    reps = []
    for p in range(n):
        if cls[p] == -1:
            cls[p] = cls[S[S[p]]] = len(reps)
            reps.append(p)
    mu = len(reps)
    qs = [cls[S[p]] for p in reps]
    qt = [cls[T[p]] for p in reps]
    cs = cycles(qt)
    widths = [len(c) for c in cs]
    c4 = sum((qs[p] == p for p in range(mu)))
    c6 = sum((qt[qs[p]] == p for p in range(mu)))
    cm1 = int(S[S[0]] == 0)
    L = lcm(*widths)
    matching = [r for r in baseline['rows'] if (r['d'], r['c4'], r['c6'], r['cm1']) == (n, c4, c6, cm1) and sorted((w for w, m in r['widths'] for _ in range(m))) == widths]
    assert matching and all((r['cong'] == matching[0]['cong'] for r in matching))
    genus = (12 + mu - 3 * c4 - 4 * c6 - 6 * len(cs)) // 12
    assert all((str(genus) == r['genus'] for r in matching))
    group_namespace = group['namespace'] if 'namespace' in group else f"G{group['order']}_{group['index']}"
    ns = f"{group_namespace}_C{number}"
    indexed_partition = group.get('indexed_partition', False) and mu > 192
    partition_definition = ''
    partition_proof = 'by decide\n'
    if indexed_partition:
        flattened = [p for cycle in cs for p in cycle]
        inverse = [flattened.index(p) for p in range(mu)]
        partition_definition = function('cuspIndex', inverse, mu, mu, True, tree) + function('cuspPointAt', flattened, mu, mu, True, tree) + 'theorem cusp_index_inverse :\n' + f'    ∀ p : Fin {mu}, cuspPointAt (cuspIndex p) = p := by decide\n'
        partition_proof = ('by\n'
                           '  refine ⟨by decide, ?_, by decide⟩\n'
                           '  exact partition_from_index cusps cuspIndex cuspPointAt\n'
                           '    cusp_index_inverse (by decide)\n')
    if tree:
        path_definition = (f'def pathData : LookupTree Word :=\n'
                           f'  {lookup_tree([word(w) for w in paths(S,T)])}\n'
                           f'def path (p : Fin {n}) : Word := tableLookup pathData p.val\n')
        path_argument = 'path p'
    elif balanced:
        path_definition = (f'def path (p : Fin {n}) : Word :=\n'
                           f'  {balanced_lookup([word(w) for w in paths(S,T)])}\n')
        path_argument = 'path p'
    else:
        path_definition = f'def paths : Array Word := #[{",".join(word(w) for w in paths(S,T))}]\n'
        path_argument = "paths[p.val]'(by simpa [paths] using p.isLt)"
    out = [f'-- {baseline["group"]}, component {number}; d={n}.\n', f'namespace {ns}\n', perm('S', S, balanced, tree), perm('T', T, balanced, tree), (f'theorem action_relations : (∀ p, S (S (S (S p))) = p) ∧\n'
           f'    (∀ p, act S T p [s,t,s,t,s,t] = S (S p)) := by decide\n'), path_definition, (f'theorem transitive_certificate :\n'
           f'    ∀ p : Fin {n}, act S T 0 ({path_argument}) = p := by decide\n'), function('cls', cls, n, mu, balanced, tree), function('rep', reps, mu, n, balanced, tree), perm('qS', qs, balanced, tree), perm('qT', qt, balanced, tree), ('theorem central_quotient :\n'
           '    (∀ p, cls (S (S p)) = cls p) ∧\n'
           '    (∀ q, cls (rep q) = q) ∧\n'
           '    (∀ p, rep (cls p) = p ∨ rep (cls p) = S (S p)) ∧\n'
           '    (∀ p, cls (S p) = qS (cls p)) ∧\n'
           '    (∀ p, cls (T p) = qT (cls p)) := by decide\n'), (f'theorem quotient_exact (p q : Fin {n}) :\n'
           f'    cls p = cls q ↔ q = p ∨ q = S (S p) :=\n'
           f'  central_fibers (fun p => S (S p)) action_relations.1 cls rep\n'
           f'    central_quotient.1 central_quotient.2.2.1 p q\n'), f'theorem central_sign : ∀ p, S (S p) {"=" if cm1 else "≠"} p := by decide\n', (f'theorem elliptic_counts :\n'
           f'    ((List.finRange {mu}).filter (fun p => qS p == p)).length = {c4} ∧\n'
           f'    ((List.finRange {mu}).filter (fun p => qT (qS p) == p)).length = {c6} := by decide\n'), f'def cusps : List (List (Fin {mu})) := {literal(cs)}\n', partition_definition, (f'theorem cusp_certificate :\n'
           f'    cusps.all (follows qT) = true ∧\n'
           f'    (∀ p : Fin {mu}, (cusps.flatten.filter (· == p)).length = 1) ∧\n'
           f'    cusps.map List.length = {literal(widths)} := ') + partition_proof, (f'theorem genus_arithmetic : (12 * {genus} : Int) =\n'
           f'    12 + {mu} - 3 * {c4} - 4 * {c6} - 6 * {len(cs)} := by decide\n'), f'theorem cusp_lcm : ({literal(widths)} : List Nat).foldl Nat.lcm 1 = {L} := by decide\n']
    obstructed = []
    if not matching[0]['cong']:
        for N in [L] if cm1 else [L, 2 * L]:
            a, b = collision(S, T, N)
            out += [f'def wordA{N} : Word := {word(a)}\n', f'def wordB{N} : Word := {word(b)}\n', (f'theorem no_factor_mod{N} :\n'
                    f'    ¬ ∃ f : ResidueMatrix {N} → Fin {n},\n'
                    f'      ∀ w : Word, f (matrixOf {N} (by decide) w) = act S T 0 w :=\n'
                    f'  collision_obstructs (by decide) S T 0 wordA{N} wordB{N} (by decide) (by decide)\n'), f'#print axioms no_factor_mod{N}\n']
            obstructed.append(N)
    out += [f'#print axioms transitive_certificate\n', f'end {ns}\n\n']
    return (''.join(out), {
        'group': baseline['group'],
        'component': number,
        'degree': n,
        'psl_degree': mu,
        'c4': c4,
        'c6': c6,
        'cm1': cm1,
        'widths': widths,
        'genus': genus,
        'obstructed_moduli': obstructed,
    })

def main():
    groups = [json.loads(l) for l in (ROOT / 'results/gap-actions.jsonl').read_text().splitlines()]
    baseline = {(g['order'], g['i']): g for g in map(json.loads, (ROOT / 'results/gap-baseline.jsonl').read_text().splitlines())}
    out = [PRELUDE]
    summary = []
    for g in groups:
        assert sum((len(c['S']) for c in g['components'])) == g['pairs']
        for k, c in enumerate(g['components']):
            source, row = component(g, k, c, baseline[g['order'], g['index']])
            out.append(source)
            summary.append(row)
    out.append(AUDIT)
    (ROOT / 'lean/BaselineCertificates.lean').write_text(''.join(out))
    (ROOT / 'results/lean-certificate-inputs.json').write_text(json.dumps(summary, indent=2) + '\n')
    print((f'Generated {len(summary)} action certificates for {len(groups)} groups; '
          f'{sum(len(r["obstructed_moduli"]) for r in summary)} obstruction witnesses. '
          'Run bash lean/check.sh to verify.'))
if __name__ == '__main__':
    main()
